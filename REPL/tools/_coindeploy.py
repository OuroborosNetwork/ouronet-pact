#!/usr/bin/env python3
"""_coindeploy.py -- emit the `coin` upgrade transaction, and keep it honest.

    python3 REPL/tools/_coindeploy.py --write    regenerate the artefact
    python3 REPL/tools/_coindeploy.py --check    offline; fatal inside _gate.py

WHAT IT EMITS. `Deploy/PureV26/00_deploy.pact` = header + `00_StoaSandbox/coin.pact` VERBATIM +
the vault counter repair as a TOP-LEVEL expression. One transaction, sent to all ten chains.

WHY THE ARTEFACT IS GENERATED RATHER THAN HAND-WRITTEN. It was hand-assembled until 2026-11-09,
which made it the only file in `Deploy/` that nothing diffed against its source -- exactly the gap
`_deploybundle.py --check` was added to close for every other deploy file. A hand-copied module
body drifts the first time someone edits `coin.pact` and forgets, and the symptom is not an error:
it is shipping a module that is not the one the 32,000 gate assertions ran against.

WHY THE REPAIR IS NOT A FUNCTION ON THE MODULE (owner ruling, 2026-11-09). It runs ONCE. A
deployed Pact module can never have a definition removed, so a one-shot migration kept inside
`coin` would be permanent dead surface on all ten chains, forever. It therefore ships as a
top-level `let` in this transaction instead.

THAT IS ONLY SAFE BECAUSE OF THREE MEASURED FACTS, each of which was checked rather than assumed:

  1] A TOP-LEVEL EXPRESSION IN THE UPGRADE TRANSACTION HOLDS MODULE ADMIN. Defining the module
     evaluates its governance, which grants admin for the rest of the transaction -- so `keys` and
     `update` on the module's own tables succeed from outside it. Without that this design is
     impossible, not merely inelegant.

  2] EVERY VAULT READER ENFORCES `UEV_ChainZero`, so the chain-id test must come FIRST and the
     readers must sit inside the else branch. The UrStoa vault is chain-0 only (`USV` is written
     by `XM_InitialiseUrStoaVault`, reachable only from `A_InitialiseStoaChain`, which opens with
     `(UEV_ChainZero)`), so chains 1-9 have the TABLE and NO ROW. An `update ... USV` there fails
     with "row not found", and because the repair rides INSIDE the upgrade transaction that
     failure would take the MODULE UPGRADE DOWN WITH IT on nine chains -- leaving the network
     split across two coin versions with cross-chain broken. A worse outage than the one this
     file exists to prevent.

  3] THE MODULE HASH IS COMPUTED OVER THE `(module ...)` FORM, NOT THE TRANSACTION. Appending
     this block changes no hash, so an identical file yields an identical `describe-module` hash
     on all ten chains, which is what cross-chain transfers require.

AND IT IS GATE-TESTED, which a deploy file normally is not. `REPL/CANARY-coin-upgrade.repl` loads
THIS ARTEFACT as the upgrade -- not `coin.pact` -- so the shipped repair block executes inside the
gate, against a vault row written by the PRE-UPGRADE module. That is the one state no ordinary
fixture can build (every other suite loads the current module first, and `insert` always supplies
every field, so a fresh row can never be missing one). Moving the repair out of the module without
moving the tests onto the artefact would have turned 9 assertions into untested code that runs
once, with admin rights, on ten chains.
"""
import io, os, re, sys

ROOT     = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
COIN     = os.path.join(ROOT, "00_StoaSandbox", "coin.pact")
ARTEFACT = os.path.join(ROOT, "Deploy", "PureV26", "00_deploy.pact")

HEADER = r''';; ═══════════════════════════════════════════════════════════════════════════
;;  StoaChain — coin contract upgrade  ·  ONE ATOMIC TRANSACTION
;;  Send this SAME FILE to ALL TEN CHAINS (0-9), as a single transaction each.
;;
;;  GENERATED by `python3 REPL/tools/_coindeploy.py --write`. Do not hand-edit:
;;  the module body below is `00_StoaSandbox/coin.pact` verbatim, and `--check`
;;  is fatal in the gate, so an edit here is reverted rather than shipped.
;;
;;  *** THE MODULE UPGRADE AND THE VAULT REPAIR ARE ONE TRANSACTION. ***
;;  *** SPLITTING THEM HALTED STOACHAIN ON 2026-11-09 AND COST A ROLLBACK. ***
;;
;;  WHY. The upgrade adds `dormant-claim-count` to UrStoaVaultSchema, and chain
;;  0's `coinbase` injects the UrStoa emission through `XI_URV|Inject`, which
;;  restores the claimant count and therefore READS that field. The USV row
;;  predates it, and NOTHING defaults an absent COLUMN: `with-default-read`
;;  defaults an absent ROW, and `try` does not catch the failure either — both
;;  measured, `REPL/modules/S1-UNCLAIMED.repl` <<TX-S1-COL>>. Sent as two
;;  transactions, the upgrade lands, every subsequent coinbase aborts, chain 0
;;  stops producing blocks, and the braid freezes behind it — at which point the
;;  repair can no longer be submitted AT ALL, because a transaction needs a
;;  block and a block needs the coinbase.
;;
;;  TWO INDEPENDENT DEFENCES, because one was not enough:
;;    1] `UR_URV|VaultDormantCount` reads the row as an OBJECT and tests
;;       `contains` before `at`, so a missing column reads 0 instead of
;;       aborting. A read on the COINBASE PATH has no error tolerance
;;       whatsoever and must be the most defensive read in the contract.
;;    2] the repair runs in THIS transaction, so the column exists from the
;;       first block the new module is live.
;;
;;  THE REPAIR IS A TOP-LEVEL BLOCK, NOT A MODULE FUNCTION (owner ruling,
;;  2026-11-09). It runs once, and a deployed Pact module can never have a
;;  definition removed — a one-shot migration kept inside `coin` would be
;;  permanent dead surface on all ten chains, forever. It works because
;;  defining the module evaluates its governance, which grants MODULE ADMIN for
;;  the rest of the transaction, so `keys` and `update` on the vault tables
;;  succeed from outside the module.
;;
;;  ALL TEN CHAINS, SIMULTANEOUSLY. The module hash is computed over the MODULE,
;;  not the enclosing transaction, so appending the repair does NOT change it —
;;  an identical file gives an identical hash on every chain, which is what
;;  cross-chain transfers require. The repair is a NO-OP off chain 0 (the vault
;;  exists only there; every vault reader enforces `UEV_ChainZero`). It must
;;  no-op rather than abort, or it would take the module upgrade down with it on
;;  nine chains.
;;
;;  WHAT THE REPAIR FIXES — more than the missing column, because more than the
;;  column is wrong. Measured on chain 0: six user rows, five holding stake,
;;  five owed something, and a STORED `unclaimed-count` of SIX. The sixth row
;;  holds neither stake nor pending — a decrement that should have fired never
;;  did. All three counters are RECOMPUTED from the user table:
;;      nzs-count           5   (unchanged, recomputed for safety)
;;      unclaimed-count     6 -> 5   (drops the stale orphan)
;;      dormant-claim-count     -> 0   (column created)
;;
;;  BASED ON THE LIVE CHAIN, NOT THE REPO COPY. `(at "code" (describe-module
;;  "coin"))` was fetched and diffed: the live module carried an `@event` on
;;  `BULK_TRANSFER_DETAIL_ANEW` that the repo copy had lost. Shipping the repo
;;  version would have silently removed it.
;;
;;  UPGRADE — `coin` is already deployed everywhere, so NO table is created.
;;  ROOT namespace: deliberately no `(namespace ...)` line.
;;  SIGNING: a STOA master keyset (`stoa_master_one` .. `five`, keys-any).
;; ═══════════════════════════════════════════════════════════════════════════

'''

REPAIR = r''';; ═══════════════════════════════════════════════════════════════════════════
;;  THE REPAIR — part of THIS transaction, and deliberately NOT a module
;;  function: it runs once, and Pact cannot remove a definition from a deployed
;;  module. Idempotent (it RECOUNTS, never increments), so a re-sent transaction
;;  is harmless.
;;
;;  THE CHAIN-ID TEST MUST COME FIRST. Every vault reader below enforces
;;  `UEV_ChainZero`, and chains 1-9 have the vault TABLE with NO row — so on
;;  those chains this must return without touching anything. An abort here
;;  would take the module upgrade down with it on nine chains.
;;
;;  `keys` and `update` on `coin`'s own tables work from out here because
;;  defining the module above evaluated its governance, which grants MODULE
;;  ADMIN for the remainder of this transaction.
;;
;;  Verify afterwards with a /local read:  (coin.URC_URV|VaultCounterAudit)
;;  -> "healthy": true, and stored-* equal to true-* for all three counters.
;; ═══════════════════════════════════════════════════════════════════════════
(if (!= (at "chain-id" (chain-data)) "0")
    "No UrStoa vault on this chain -- counter repair not applicable"
    (let*
        (
            (accts:[string] (keys coin.URV|UrStoaVaultUser))
            (rps:decimal (coin.UR_URV|VaultRPS))
            ;;NZS: rows holding stake.
            (staked:[string]
                (filter (lambda (a:string) (> (coin.UR_URV|UserSupply a) 0.0)) accts))
            ;;OWED: rows with a positive claimable -- stored pending PLUS what the
            ;;current index owes them. Computed, not read: `pending-rewards` is only
            ;;materialised at a checkpoint, so it reads 0 for an ordinary staker.
            (owed:[string]
                (filter
                    (lambda (a:string)
                        (> (+ (coin.UR_URV|UserPendingRewards a)
                              (* (- rps (coin.UR_URV|UserLastRps a))
                                 (coin.UR_URV|UserSupply a)))
                           0.0))
                    accts))
            ;;DORMANT: owed but no longer accruing -- the accounts `nzs-count` cannot
            ;;see, which is why resetting the claimant count to `nzs` alone is unsafe.
            (dormant:[string]
                (filter (lambda (a:string) (= (coin.UR_URV|UserSupply a) 0.0)) owed))
        )
        (update coin.URV|UrStoaVault coin.USV
            {"nzs-count"           : (length staked)
            ,"unclaimed-count"     : (length owed)
            ,"dormant-claim-count" : (length dormant)}
        )
        (format "UrStoaVault counters repaired from {} user row(s): nzs-count={}, unclaimed-count={}, dormant-claim-count={}"
            [(length accts) (length staked) (length owed) (length dormant)])
    )
)
'''


def build():
    coin = io.open(COIN, encoding="utf8").read()
    if "defun UM_URV|RepairVaultCounters" in coin:
        sys.exit("coin deploy: coin.pact still defines UM_URV|RepairVaultCounters. The repair "
                 "moved OUT of the module (owner ruling 2026-11-09); remove it or this artefact "
                 "would ship the migration twice.")
    if re.search(r'^\(namespace', coin, re.M):
        sys.exit("coin deploy: coin.pact carries a `(namespace ...)` line. `coin` is a ROOT "
                 "namespace module; shipping one would deploy it somewhere else entirely.")
    return HEADER + coin.rstrip("\n") + "\n" + REPAIR


def main():
    text = build()
    if "--write" in sys.argv:
        io.open(ARTEFACT, "w", encoding="utf8").write(text)
        print(f"coin deploy: wrote {os.path.relpath(ARTEFACT, ROOT)} ({len(text):,} bytes)")
        return 0
    if "--check" in sys.argv:
        if not os.path.exists(ARTEFACT):
            print(f"coin deploy: {os.path.relpath(ARTEFACT, ROOT)} is MISSING. Run --write.")
            return 1
        have = io.open(ARTEFACT, encoding="utf8").read()
        if have != text:
            print(f"coin deploy: {os.path.relpath(ARTEFACT, ROOT)} is STALE against "
                  f"00_StoaSandbox/coin.pact ({len(have):,} bytes on disk, {len(text):,} "
                  f"regenerated).")
            print("  The shipped module body is no longer the one the gate tested.")
            print("  Regenerate with:  python3 REPL/tools/_coindeploy.py --write")
            return 1
        print(f"coin deploy: clean -- 00_deploy.pact is coin.pact verbatim plus the repair block "
              f"({len(text):,} bytes)")
        return 0
    print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main())
